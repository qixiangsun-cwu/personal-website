import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const here = path.dirname(url.fileURLToPath(import.meta.url));
const PYSRC = JSON.parse(fs.readFileSync(path.join(here, "..", "src", "pysrc.json"), "utf8"));

function beforeFunc(src, pat) {
  const lines = src.split(/\r?\n/);
  const i = lines.findIndex((l) => l.match(pat));
  return lines.slice(0, i).join("\n");
}

function stripInlineComment(line) {
  let q = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === "\\") { i++; continue; }
      if (c === q) q = null;
      continue;
    }
    if (c === '"' || c === "'") { q = c; continue; }
    if (c === "#") return line.slice(0, i);
  }
  return line;
}

export function py2js(py) {
  const lines = py.split(/\r?\n/);
  const kept = [];
  let inDoc = false;
  let inTriple = false;
  let buf = null;
  let key = null;
  for (const raw of lines) {
    if (inTriple) {
      const end = raw.indexOf('"""');
      if (end < 0) {
        buf.push(raw);
        continue;
      }
      buf.push(raw.slice(0, end));
      const js = buf.join("\\n");
      kept.push(key + '"' + js.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"');
      buf = null;
      key = null;
      inTriple = false;
      continue;
    }
    const quotes = (raw.match(/"""/g) || []).length;
    if (inDoc) {
      if (quotes > 0) inDoc = false;
      continue;
    }
    if (/^\s*"""/.test(raw)) {
      if (quotes % 2 === 1) inDoc = true;
      continue;
    }
    if (/^\s*#/.test(raw)) continue;
    if (/^\s*(import |from |if __name__|def |async def )/.test(raw)) continue;
    const m = raw.match(/^(\s*)([A-Za-z_]\w*)[ \t]*=[ \t]*"""(.*)$/);
    if (m) {
      const [, ind, name, rest] = m;
      if (rest.includes('"""')) {
        const end = rest.indexOf('"""');
        const text = rest.slice(0, end);
        kept.push(ind + name + ' = "' + text.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"');
      } else {
        buf = [rest];
        key = ind + name + " = ";
        inTriple = true;
      }
      continue;
    }
    const line = stripInlineComment(raw);
    if (!line.trim()) continue;
    kept.push(line);
    if (/"""/.test(raw)) console.error("DBG triple leftover:", JSON.stringify(raw.slice(0, 60)));
  }
  if (inTriple) console.error("WARN: unterminated triple-quoted string");

  const body = kept.map((l) => l);
  let out = "";
  for (let i = 0; i < body.length; i++) {
    const l = body[i];
    const next = body[i + 1];
    out += l;
    if (next && /["'\]}]\s*$/.test(l) && /^\s*r?["'{[]/.test(next)) out += " +";
    out += "\n";
  }
  const compIdx = out.search(/^_BY_KEY = \{/m);
  if (compIdx > 0) out = out.slice(0, compIdx);
  out = out.replace(/(^|\n)([A-Z_][A-Z0-9_]*)(\s*=\s*)/g, "$1export const $2 = ");
  out = out.replace(/^(?:export const )?STRICT = os\.getenv\([^\n]*$/m,
    'export const STRICT = String(globalThis.REDLINE_STRICT || "off").toLowerCase() === "on";');
  out = out.replace(/\bNone\b/g, "null").replace(/\bTrue\b/g, "true").replace(/\bFalse\b/g, "false");
  out = out.replace(/(^|[\s(\[,{:=])r(["'])/g, "$1$2");
  out = out.replace(/re\.compile\(/g, "new RegExp(");
  out = out.replace(/(\r?\n)(\{\r?\n)/g, "$1    $2");
  return out;
}

function tidy(js) {
  return js
    .split(/\r?\n/)
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l) => l.trim() !== "")
    .join("\n");
}

const HEAD = "// AUTO-GENERATED by worker/scripts/gen-literals.mjs - do not edit\n/* eslint-disable */\n";

const parts = [];
parts.push("// ==== reply_policy.py literals ====\n" + tidy(py2js(beforeFunc(PYSRC["reply_policy.py"], /^def /))) + "\n");
parts.push("// ==== redline.py literals ====\n" + tidy(py2js(beforeFunc(PYSRC["redline.py"], /^(async )?def _negated/))) + "\n");
parts.push("// ==== prompts.py literals ====\n" + tidy(py2js(beforeFunc(PYSRC["prompts.py"], /^def /))) + "\n");

const out = HEAD + parts.join("\n");
const dest = path.join(here, "..", "src", "literals.gen.js");
fs.writeFileSync(dest, out, "utf8");
console.log("written", out.length, "bytes");

