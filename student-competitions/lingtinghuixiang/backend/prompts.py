# ============ 七、组装辅助 ============
def inbound_prompt(company: str, shop: str, hotline: str, rag: str = "") -> str:
    """来电系统提示词；rag 为空时给出「本轮无命中」的引导句。"""
    return SYS_TEMPLATE_INBOUND.format(
        company=company, shop=shop, hotline=hotline,
        rag=rag or ("（本轮无命中知识：按常识引导登录京麦后台查看驳回意见，"
                    f"或拨打 {hotline} 核实）"))


def state_hint_of(state: str) -> str:
    """状态 → 本轮推进要求；未登记的状态返回空串（与迁移前一致）。"""
    return STATE_HINTS.get(state, "")


def tool_desc_of(name: str, fallback: str = "") -> str:
    """工具描述优先取本文件（RSI 可改），缺省回退调用方字面量。"""
    return TOOL_DESC.get(name) or fallback
