def identity_kind(text: str) -> str:
    """身份确认段（S1）这句话属于哪一类；返回 '' 表示泛应答 / 未识别。

    判定优先级：口误更正 → 肯定自证 → 细分规则（含否认）。
    「不是，我就是商家本人」这类先否认后自证的句子按 AFFIRM 处理，绝不误挂。
    """
    t = (text or "").strip()
    if not t:
        return ""
    # 11/15 真机修复③：「不是不是」「不不」单独出现是**加强否认**，不是口误更正。
    # 旧实现一命中就短路返回 AFFIRM，商家连说两次「不是」反而被当成身份确认。
    # 只有同时带肯定自证（「不是不是，我就是商家本人」）才按 AFFIRM 处理。
    if _S1_CORRECT_RE.search(t):
        if _S1_SELFPROOF_RE.search(t):
            return "AFFIRM"
        # 「不不」「不对不对」是加强否认；不能因为像口误就落到二次确认
        if _S1_DENY_BRIEF_RE.match(t):
            return "DENY"
    if _S1_SELFPROOF_RE.search(t):
        return "AFFIRM"
    for kind, rx in _IDENTITY_RULES:
        if rx.search(t):
            return kind
    return ""


def contact_bits(contact: str) -> tuple:
    """把工单对接人拆成 (原样, 姓, 称呼)。念姓氏不念全名，避免念错/过度暴露。"""
    c = (contact or "").strip().strip("，,、 ")
    if not c or c in ("未提供", "无", "-", "—", "未知"):
        return ("", "", "")
    c = c[:6]
    surname = c[0]
    if len(c) > 1 and c[1:] in _CONTACT_TITLE:
        return (c, surname, c)
    for ttl in _CONTACT_TITLE:
        if c.endswith(ttl) and len(c) > len(ttl):
            return (c, c[0], c)
    return (c, surname, surname)


