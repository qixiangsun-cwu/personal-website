def is_distrust(text: str, in_trust_ctx: bool = False) -> bool:
    """明确表态不信任（「不想相信你」「我不」）。

    in_trust_ctx=True 表示刚发生过不信任，此时「我不 / 不要」也算继续不信。
    """
    t = (text or "").strip()
    if not t or len(t) > 24:
        return False
    if _DISTRUST_STRONG_RE.search(t):
        return True
    if in_trust_ctx and _DISTRUST_BRIEF_RE.match(t):
        return True
    return False


def is_trust_confirm(text: str) -> bool:
    """商家表示愿意相信 → 继续推进（否定优先，业务词不算信任表态）。"""
    t = text or ""
    if is_trust_doubt(t) or is_distrust(t, in_trust_ctx=True):
        return False
    if _DISTRUST_BUSINESS_RE.search(t):
        return False
    return bool(_TRUST_OK_RE.search(t))


