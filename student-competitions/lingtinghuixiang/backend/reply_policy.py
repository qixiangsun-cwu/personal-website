# ④ 数字员工身份真实性质疑（11/15 真机修复④）
#    旧逻辑只在 S1「商家身份确认」段调用 identity_kind；到了答疑段，
#    「我怀疑你的身份，你是诈骗的吗？」被 findfault_hit 判成找茬、
#    被 redline 判成辱骂(ABUSE)，或落成 HESITANT「哪一部分还有疑虑」。
#    这里提供**与阶段无关**的纯判定，供 agent 在通用分支里优先路由。
# =====================================================================
_AGENT_IDENTITY_CORE_RE = re.compile(
    r"(?:你|您|你们|对方|来电|这边).{0,4}(?:的)?身份"
    r"|身份.{0,8}(?:真实性|真假|是真是假|可靠|可信|存疑)"
    r"|(?:怀疑|质疑|不确定|核实|验证|确认|证实).{0,10}身份"
    r"|诈骗|骗子|钓鱼|冒充|假冒|冒名|李鬼|是不是真的"
    r"|机器人|数字人|数字员工|智能语音|真人吗|是真人"
    r"|(?:你|您|你们)(?:是|是不是|是吗|是吧).{0,4}(?:京东|平台|官方)"
    r"|京东(?:的)?(?:吗|吧|呀|么|嘛|人|员工|客服|官方|打来的)|人机"
    r"|工号|哪个部门|什么部门|哪个平台|哪里的|你叫什么|你是谁|贵姓"
    r"|(?:怎么|如何|凭什么).{0,4}(?:证明|核实|验证|确认)"
    r"|官方(?:的吗|吗)|真的假的|身份真实")
# 业务疑问词：出现这些且没有明确的身份强信号时，不算身份质疑
# （「我的材料是不是真的」「这个资质是假的吗」是审核结论疑问，不是身份核实）
_AGENT_IDENTITY_VETO_RE = re.compile(
    r"造假|伪造|作假|假材料|假证|授权书|商标|类目|发票|费用|"
    r"怎么登录|怎么提交|怎么补|哪里提交|多久|什么时候能|材料|资质")


def is_agent_identity_doubt(text: str) -> bool:
    """商家质疑**数字员工本人**身份真实性（≠质疑审核结论、≠泛泛不信任）。

    用于所有业务阶段；「你是说我造假吗」「我不相信你」分别由 FAKE_DOUBT /
    不信任三级链处理，不在这里抢。
    """
    t = (text or "").strip()
    if not t or len(t) > 45 or not _AGENT_IDENTITY_CORE_RE.search(t):
        return False
    if _AGENT_IDENTITY_VETO_RE.search(t) and not re.search(
            r"身份|诈骗|骗子|冒充|工号|机器人|官方|哪个部门|怎么证明", t):
        return False
    return True


