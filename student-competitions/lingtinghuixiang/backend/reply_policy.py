# 长词优先，避免「没有了」被「没有」拆断后残留一个「了」
_NO_MORE_TOKEN_RE = re.compile(
    "|".join(re.escape(w) for w in sorted(_NO_MORE_TOKENS, key=len, reverse=True)))
# 句首语气词 / 句尾附和词 / 标点（ASR 口语噪声）
_NO_MORE_NOISE_RE = re.compile(
    r"[\s，,。！!、；;：:…~\.·\-—]+"
    r"|(?:谢谢|多谢|感谢|好吧|行吧|对对|是的|对了|那个|这个|然后|就是|"
    r"哎|唉|嗯|呃|额|噢|哦|啊|嘿|喂|哈|诶|欸|昂|恩|那|好|行|对|吧|呀|"
    r"嘛|呢|啦|咯|喽|呗|是|没|ok|OK|也|还|了|真|确实|"
    # 11/19：「我没疑问了」剥掉 token 后剩「我」不算剩余内容（实测答疑灯不亮）
    r"我|您|你)")
# 剔除收束词后仍出现 → 不是「无疑问」，而是追问 / 转折 / 新业务问题
_NO_MORE_VETO_RE = re.compile(
    r"[?？]|怎么|怎样|为什么|为啥|哪|谁|多少|能不能|可不可以|是否|是不是|有没有|"
    r"再讲|再说|还有|另外|等一下|我想问|请问|不过|但是|可是|我想|我要|麻烦|帮我|"
    r"登录|后台|提交|材料|资质|驳回|审核|申诉|费用|发票|京麦|补齐|补充|疑问|问题")


def no_more_plain(text: str) -> bool:
    """商家明确表示「没有更多疑问 / 听明白了」，不含任何业务承诺。

    兼容 ASR 口语：语气词前缀、句尾附和、重复叠词、同音异字（内部先归一）。
    """
    s = asr_norm((text or "").strip())
    if not s or "?" in s or "？" in s:
        return False
    if not _NO_MORE_TOKEN_RE.search(s):
        return False
    rest = _NO_MORE_TOKEN_RE.sub("", s)
    if _NO_MORE_VETO_RE.search(rest):
        return False
    return not _NO_MORE_NOISE_RE.sub("", rest)


