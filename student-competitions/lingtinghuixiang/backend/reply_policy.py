# 【11/22】「求解释」句式：<1~6 个字的词><是什么/是啥/啥意思/什么意思/…>。
# 这类句子哪怕一个业务词都没命中，也很可能是「ASR 把业务词听错」造成的
# （续脉→京麦、青麦→京麦…），因此不判闲聊，交给答疑段让模型猜。
# 刻意只认「是/啥意思」这种**解释型**问法：天气、吃喝、闲聊都不会长这样，
# 所以不会把「今天天气不错啊 / 晚上吃什么好 / 你们那下雨没」放进来。
_LOOKUP_ASK_RE = re.compile(
    r"[\u4e00-\u9fa5A-Za-z]{1,6}(?:是什么|是啥|啥意思|什么意思|是什么东西|啥东西|"
    r"是干什么的|是干啥的|干什么用的|干啥用的)")
# 「什么叫X / 啥叫X / 何为X」同样是在问概念（「什么叫资质造假？」不该被判成要求造假）
_LOOKUP_WHAT_RE = re.compile(r"什么叫|啥叫|何为|何谓|什么是|啥是|是啥子|咋理解|怎么理解")


def is_lookup_question(text: str) -> bool:
    """整句是否在**求解释/问概念**（而不是在提要求）。

    用于两处「负向判定」的豁免：
      · 闲聊判定：ASR 把业务词听错时，问句不该被拒答（续脉/去脉 = 京麦）；
      · 红线判定：「什么叫资质造假」是在问概念，不是「要求造假」——
        旧逻辑只看关键词，把提问教育了一顿还记了一条违规（污染合规率）。
    """
    s = (text or "").strip()
    if not s:
        return False
    return bool(_LOOKUP_ASK_RE.search(s) or _LOOKUP_WHAT_RE.search(s))


# 【11/22 真机修复·打招呼被当成闲聊】
# 真机：商家接起来说「哇塞。你好。」，AI 回「这个我这边不方便展开。咱们回到您咨询的问题上」
# —— 招呼都不会打，像审问。原因是 offtopic_generic 只看"有没有业务信号"，
# 一句话里没有"资质/驳回/材料"就判闲聊，打招呼天然中招。
# 这里把"整句只由招呼/语气词组成"的情况单独认出来，不按闲聊处理。
_SOCIAL_TOKENS = re.compile(
    r"(喂|你好|您好|哈喽|hello|hi|在吗|在不在|在的|哇塞|哎哟|哦豁|嗯哼|嗯|哦|噢|啊|"
    r"哈+|嘿|早|早上好|中午好|下午好|晚上好|好|的|呀|呢|吧|嘛|了|是|对|说|听|到)")
_SOCIAL_STRIP = re.compile(r"[。，！？、,.!?~～\s…—-]")


def is_social_greeting(text: str) -> bool:
    """整句只是打招呼/应声（「哇塞。你好。」「喂」「嗯嗯」）→ 不是闲聊，别拿"不方便展开"怼回去。"""
    s = _SOCIAL_STRIP.sub("", asr_norm((text or "").strip()))
    if not s or len(s) > 12:
        return False
    if _BUSINESS_SIGNAL_RE.search(s):
        return False
    return _SOCIAL_TOKENS.sub("", s) == ""


def offtopic_generic(text: str) -> bool:
    """泛化闲聊判定：无业务信号 + 非流程应答 = 闲聊。

    只在 redline 词库**未命中**时作为兜底调用，接管词库外的一切闲聊
    （护肤偏方、人生道理、热点八卦……），不再依赖逐词补充。
    """
    s = asr_norm((text or "").strip())
    if len(s) < 2:
        return False
    # 纯招呼/应声豁免（11/22）：必须在闲聊判定之前
    if is_social_greeting(s):
        return False
    # 纯应答豁免（好的/明白了/是的/谢谢您了……）：短语全由应答词拼成 → 不是闲聊。
    # 必须在一切判定之前，否则 vio 分支会抢在流程应答分支前面把收尾句当闲聊拉回。
    if _is_pure_ack(s):
        return False
    # 业务信号优先豁免
    if _BUSINESS_SIGNAL_RE.search(s):
        return False
    # 【11/22 真机修复·ASR 听错不该判闲聊】「X是什么 / X是啥意思」这类**求解释**句式，
    # 即使没命中任何业务词也不按闲聊处理，交给答疑段由模型判断。
    # 原因：词表永远追不上 ASR 的错法（「续脉」=「京麦」只是其中一种）；一旦听错就
    # 把业务提问判成闲聊、回「这个我这边不方便展开」，商家会觉得 AI 在敷衍。
    # 「猜一下这是哪个业务词」恰恰是模型的强项，这条通道就是留给它的。
    if _LOOKUP_ASK_RE.search(s):
        return False
    if _LOOKUP_WHAT_RE.search(s):
        return False
    # 各类流程应答（身份确认/整改承诺/无疑问收束/改约/不信任/造假质疑/身份质疑）
    if identity_kind(s):
        return False
    if will_promise_hit(s) or no_more_plain(s) or no_time_hit(s):
        return False
    if is_fake_doubt(s) or is_agent_identity_doubt(s):
        return False
    if is_trust_doubt(s) or is_distrust(s, in_trust_ctx=True) or findfault_hit(s):
        return False
    if is_name_challenge(s):
        return False
    # 显式流程语境与日期/数字（改约给日期、报单号、报电话）
    if _FLOW_VETO_RE.search(s):
        return False
    return True


