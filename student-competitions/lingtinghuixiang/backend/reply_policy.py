# ⑤b 11/15 真机修复⑥：商家说「哪天都没空」= 全时段无空 → 直接转人工
#
# 真机复盘：商家连说「哪一天都没空。」「我哪天都没空。」，AI 仍按普通改约
# 两次追问「您看哪天方便？」「那您大概哪天能腾出时间？」，第三次才礼貌收线。
# 「没有哪一天方便」本身已经排除了改约的可能，继续问日期属于机械复读；
# 旧链路只区分 no_time（最近没空 → 需问日期），没有「全时无空」这一档，
# 且 _reschedule_asked>=2 的收线只播「方便的时候随时提交」，并不转人工。
#
# 本函数是纯规则强证据：命中即视为「无可约时间」，与语义标签解耦，
# 离线回放与线上口径一致。普通改约（最近/今天/这两天没空）、同句给了具体日期、
# 疑问、双重否定一律否决，避免把还能约时间的商家直接转走。
# =====================================================================
_NO_DAY_FREE_SCOPE_RE = re.compile(
    r"哪天|哪一天|哪一日|每天|天天|每日|整天|成天|任何时候|啥时候|什么时候|"
    r"一直|从来|根本|完全|始终|永远|全年|周周|月月")
_NO_DAY_FREE_NO_RE = re.compile(
    r"没(?:有)?(?:空|时间|工夫|功夫)|不(?:太|大|怎么|是|够|很)?方便|"
    r"去不了|去不成|腾不出|抽不出|抽不开|忙|不行")
_NO_DAY_FREE_VETO_RE = re.compile(
    r"[?？]|不是|不一定|未必|不见得|也不至于|哪天都行|哪天都可以|"
    r"哪天方便|什么时候方便|有空|能去|可以去|都行|随便哪天|"
    r"\d{1,2}[日号]|[一二三四五六七八九十]{1,3}[日号]|"
    r"(?:下下|下|这|本)?(?:周|週|礼拜)[一二三四五六日天]|"
    r"后天|明天|今日|今天|下个月|月底|月初")


def no_day_free_hit(text: str) -> bool:
    """商家明确表示「哪一天都没空」——无可约时间，应转人工而非继续问日期。

    正例：哪一天都没空 / 我哪天都没空 / 每天都没空 / 一直没空 /
          根本抽不出时间 / 我什么时候都不方便 / 嗯，我哪天都没空。
    反例：最近没空 / 今天没空 / 这两天不方便 / 改天吧 / 哪天方便？ /
          不是哪天都没空 / 我哪天都行 / 十八号吧 / 我哪天都没空，十八号吧。
    """
    s = asr_norm((text or "").strip())
    if not s or len(s) > 40 or _NO_DAY_FREE_VETO_RE.search(s):
        return False
    return bool(_NO_DAY_FREE_SCOPE_RE.search(s) and _NO_DAY_FREE_NO_RE.search(s))


