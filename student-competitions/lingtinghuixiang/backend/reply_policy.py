def asr_norm(text: str) -> str:
    """把常见同音误转写归一成正确写法；未命中的文字原样返回。

    11/19：「京麦」用**组合正则**覆盖全部声母混淆空间（j/q/x 首字 × 麦/卖/脉/迈/唛
    尾字共 115 种组合），不再逐词枚举——实测商家打字/ASR 产出了静脉、经脉、清迈、
    星脉等十余种写法，枚举永远追不完。真实词安全性已离线验证：青霉素/轻慢/经济/
    经营/清明/型号/行销等全部不误伤（第二字不在尾字集内）。
    """
    t = text or ""
    if not t:
        return t
    # 11/19：「什么意思」的 ASR 错字全家桶（和一微/和意味/何意味/啥意味……每次
    # 拼法都不同，逐词枚举追不完）——改用**整句形态匹配**：整句就是
    # 「0~2 个前缀字 + 一/以 + 微/味/位/未/为/卫 + 语气词/标点」→ 整句归一。
    # 锚定整句（允许尾部语气词/标点），「意味深长」这类真实词不受影响。
    t = re.sub(r"^[\u4e00-\u9fa5]{0,2}[一以][微味位未为卫][啊呀吧呢哦嘛的呀。？?！!，,\s]*$",
               "什么意思啊", t)
    # 京麦：j/q/x + mai 的组合正则（资质审核电话里出现必然是京麦误写）
    #
    # 【11/22 二次修复·从"枚举字"改成"锚定句式"】
    # 第一版是往首字集里补「续徐许须…」，结果真机立刻又冒出「去脉」——证明
    # **按字枚举永远追不上听错的方式**。现在改成两条：
    #   ① 句式锚定（覆盖任意首字）：只要处在「X脉/麦/迈是什么|是啥|啥意思」这种
    #      **求解释**的句子里，X 是哪个字都无所谓 —— 业务域内没有别的「X脉」词，
    #      整句语义就是「京麦是什么意思」，归一安全且不需要枚举；
    #   ② 原有首字组合（覆盖非句式的裸词，如「静脉」「清迈」）。
    t = re.sub(r"[\u4e00-\u9fa5][麦卖脉迈唛](?=(?:是|啥|什么|干|怎|有|在|哪个|哪些))",
               "京麦", t)
    t = re.sub(r"[京静经净井惊精茎荆晶鲸青清轻晴情请星行幸兴型形"
               r"续徐许须需旭叙蓄序绪去][麦卖脉迈唛]", "京麦", t)
    for bad, good in ASR_HOMOPHONE_MAP.items():
        if bad in t:
            t = t.replace(bad, good)
    return t


