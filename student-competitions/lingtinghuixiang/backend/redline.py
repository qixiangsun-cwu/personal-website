def as_hit(key: str) -> dict:
    """按 key 构造一条「已命中」结果，供语义判定补充拦截时复用同一套话术与等级。

    用途（11/22）：关键词表会漏掉「帮我P一份授权书」这类不含"造假"字样的真请求，
    于是用「明确请求动词 + 模型确认是违规请求」双钥匙补一条命中。
    直接复用 `_hit()`，保证 level/action/reply/say/guide/close/tag/mark 等字段
    与既有红线完全一致（commit_reply / _enrich_vio / 工单卡都依赖这些字段）。
    """
    for cat in CATEGORIES:
        if cat.get("key") == key:
            return _hit(cat, "（语义判定命中·建议人工复核）", "semantic")
    return {"hit": True, "key": key, "name": key, "level": "B",
            "phrase": "（语义判定命中）", "how": "semantic",
            "action": "terminate", "reply": reply_for(key)}


def script_for(key: str) -> dict:
    """B 级三段式话术（say/guide/close/tag）；A 级返回空字典。"""
    return B_SCRIPT.get(key) or {}


def correction(key: str) -> dict:
    """纠正话术（定性 say + 引导 guide）；终止/交接由 agent 按分支决定。"""
    c = CORRECT.get(key) or {}
    if c.get("say") or c.get("guide"):
        return dict(c)
    s = B_SCRIPT.get(key) or {}
    return {"say": s.get("say", ""), "guide": s.get("guide", "")}


def is_alert(key: str) -> bool:
    """是否需要在进度条上弹【红线违规警告】卡片。"""
    return ALERT.get(key, True)


def reply_for(key: str) -> str:
    """该类别对应的完整播报文本。

    B 级 = 指出不对 + 正确引导 + 终止交接（三句）；
    A 级 = 单句拒绝 + 拉回业务。
    """
    s = B_SCRIPT.get(key)
    if s:
        return "".join([s["say"], s["guide"], s["close"]])
    return REPLY.get(key, REPLY["OVER_PROMISE"])


def _negated(text: str, start: int) -> bool:
    """命中位置前 5 字内是否有否定词。

    11/12 修一个真实漏判：「你能不能保证我这次一定过」里的「不能」不是否定，
    是「能不能」这种正反问句式。先剔掉疑问结构再看否定词，否则商家最典型的
    越权承诺问法会被当成"他自己否认"，直接漏拦。
    """
    win = text[max(0, start - 6):start]
    win = re.sub(r"(能不能|可不可以|会不会|是否|是不是|要不要|有没有|行不行|对不对|好不好)", "", win)
    return bool(_NEG.search(win))


def classify(text: str) -> dict:
    """判断商家这句话是否触碰红线。

    返回 {"hit": bool, ...}：hit=True 时带 key/name/level/action/reply/phrase/excel。
    hit=False 时返回 {"hit": False, "off_topic": bool}，方便路由把闲聊拉回正题。
    """
    t = (text or "").strip().lower()
    if not t:
        return {"hit": False}

    for cat in CATEGORIES:
        # 0) 类目级豁免（如 OVERRIDE：商家自己去后台整改是正经事，不算越权）
        if cat.get("veto"):
            vetoed = any(re.search(v, t) for v in cat["veto"])
            blocked = any(re.search(a, t) for a in cat.get("antiveto", []))
            if vetoed and not blocked:
                continue
        # 1) 关键词硬命中
        for w in cat["words"]:
            idx = t.find(w)
            if idx >= 0 and not _negated(t, idx):
                return _hit(cat, w, "keyword")
        # 2) 正则组合命中（应对「通融一哈」这类改写）
        if "patterns" in cat:
            for pat in cat["patterns"]:
                m = re.search(pat, t)
                if m and not _negated(t, m.start()):
                    return _hit(cat, m.group(0), "pattern")
    return {"hit": False}


def _hit(cat: dict, phrase: str, how: str) -> dict:
    level = "B" if (STRICT or cat["level"] == "B") else "A"
    sc = B_SCRIPT.get(cat["key"]) if level == "B" else None
    return {
        "hit": True,
        "key": cat["key"],
        "name": cat["name"],
        "level": level,
        "base_level": cat["level"],
        "excel": cat["excel"],
        "desc": cat["desc"],
        "phrase": phrase,
        "how": how,
        "action": "terminate" if level == "B" else "warn",
        "reply": reply_for(cat["key"]),
        # B 级三段式的拆分文本，前端工单/复盘可直接逐句展示「怎么指出的、怎么引导的」
        "say": (sc or {}).get("say", ""),
        "guide": (sc or {}).get("guide", ""),
        "close": (sc or {}).get("close", ""),
        # 风险标签 + 是否给该商家打特殊标记（B 级一律打标，A 级不打）
        "tag": (sc or {}).get("tag", ""),
        "mark": level == "B",
        "non_task_end": level == "B",
        # 13/13 三分支处置：本类是否弹告警卡；纠正话术（两段）
        "alert": is_alert(cat["key"]),
        "correct": correction(cat["key"]),
        "pull_back": PULL_BACK,
    }


